let lastFamPubGate = 0;
const _wFamPublish = famPublish;
famPublish = function (status, reason) {
  if (store.get('battsave', false) && status !== 'SOS' && Date.now() - lastFamPubGate < 55000) return;
  lastFamPubGate = Date.now();
  _wFamPublish(status, reason);
};

