/* ================= TELEGRAM ALERTS ================= */
$('tgToken').value = store.get('tgtoken', '');
$('tgChat').value = store.get('tgchat', '');
function tgSave() {
  store.set('tgtoken', $('tgToken').value.trim());
  store.set('tgchat', $('tgChat').value.trim());
  alert('✅ Saved on this device. SOS alerts and failed check-ins will now also go to your Telegram group — even when everyone\'s apps are closed.');
}
async function tgSend(msg) {
  const token = store.get('tgtoken', ''), chat = store.get('tgchat', '');
  if (!token || !chat) return false;
  try {
    const r = await fetch(`https://api.telegram.org/bot${token}/sendMessage`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ chat_id: chat, text: msg })
    });
    return (await r.json()).ok === true;
  } catch (e) { return false; }
}
async function tgTest() {
  store.set('tgtoken', $('tgToken').value.trim());
  store.set('tgchat', $('tgChat').value.trim());
  const ok = await tgSend('🛡️ Raksha AI test — Telegram alerts are working! You will receive SOS alerts in this chat.');
  alert(ok ? '✅ Test message sent — check your Telegram group.' : '❌ Failed. Check the token, the chat ID (usually starts with -100), and that the bot is a member of the group.');
}

/* ================= SOS WEBHOOK ================= */
$('webhookUrl').value = store.get('webhook', '');
$('webhookUrl').addEventListener('change', e => store.set('webhook', e.target.value.trim()));
function fireWebhook(reason) {
  const url = store.get('webhook', '');
  if (!url || !/^https:\/\//.test(url)) return;
  try {
    fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ event: 'sos', app: 'raksha-ai', reason, lat: S.pos?.lat ?? null, lon: S.pos?.lon ?? null, ts: Date.now() })
    }).catch(() => {});
  } catch (e) {}
}

/* ================= EMERGENCY HOOKS + INCIDENT REPORT ================= */
let emStartTs = 0, emReason = '';
const _wStartEmergency = startEmergency;
startEmergency = function (reason) {
  emStartTs = Date.now(); emReason = reason;
  _wStartEmergency(reason);
  const loc = S.pos ? `https://maps.google.com/?q=${S.pos.lat},${S.pos.lon}` : 'location unavailable';
  const t = (typeof trackerLink === 'function') ? trackerLink() : null;
  tgSend(`🚨 SOS — EMERGENCY\nTrigger: ${reason}\nLocation: ${loc}` + (t ? `\nLive tracker: ${t}` : '') + `\nTime: ${new Date().toLocaleString()}\n(Raksha AI)`);
  fireWebhook(reason);
};

const incidents = store.get('incidents', []);
$('stopEmergency').addEventListener('click', () => {
  if (!emStartTs) return;
  const durMin = ((Date.now() - emStartTs) / 60000).toFixed(1);
  const events = (typeof brainEvents !== 'undefined')
    ? brainEvents.filter(e => e.ts >= emStartTs - 60000).slice(0, 15).map(e => new Date(e.ts).toLocaleTimeString() + ' — ' + e.msg)
    : [];
  incidents.unshift({
    ts: emStartTs, dur: durMin, reason: emReason,
    lat: S.pos?.lat ?? null, lon: S.pos?.lon ?? null,
    events
  });
  store.set('incidents', incidents.slice(0, 20));
  emStartTs = 0;
  renderIncidents();
  tgSend('✅ Emergency ended — user marked safe. Duration: ' + durMin + ' min. (Raksha AI)');
});

function incidentText(inc) {
  return 'RAKSHA AI — INCIDENT REPORT\n' +
    'Date/time: ' + new Date(inc.ts).toLocaleString() + '\n' +
    'Duration: ' + inc.dur + ' minutes\n' +
    'Trigger: ' + inc.reason + '\n' +
    'Location: ' + (inc.lat ? inc.lat.toFixed(5) + ', ' + inc.lon.toFixed(5) + ' (https://maps.google.com/?q=' + inc.lat + ',' + inc.lon + ')' : 'unavailable') + '\n' +
    (inc.events.length ? '\nEvent timeline:\n' + inc.events.map(e => '• ' + e).join('\n') + '\n' : '') +
    '\nEvidence (audio/photos) is stored in the app\'s Evidence Vault / recordings list.\nGenerated by Raksha AI (open source).';
}
function renderIncidents() {
  const l = $('incidentList');
  if (!l) return;
  if (!incidents.length) return;
  l.innerHTML = '';
  incidents.forEach((inc, i) => {
    const d = document.createElement('div');
    d.className = 'rec-item';
    d.innerHTML = `<b>📋 ${new Date(inc.ts).toLocaleString()}</b> — ${esc(inc.reason)} <span class="badge">${inc.dur} min</span>`;
    const share = document.createElement('button');
    share.className = 'btn small secondary'; share.style.marginTop = '8px'; share.textContent = '📤 Share / save';
    share.onclick = () => { const t = incidentText(inc); if (navigator.share) navigator.share({ text: t }).catch(() => {}); else prompt('Copy:', t); };
    const del = document.createElement('button');
    del.className = 'btn small danger'; del.style.marginTop = '8px'; del.textContent = 'Delete';
    del.onclick = () => { incidents.splice(i, 1); store.set('incidents', incidents); $('incidentList').innerHTML = '<p class="hint">No reports.</p>'; renderIncidents(); };
    d.appendChild(share); d.appendChild(del);
    l.appendChild(d);
  });
}

/* ================= SHARE TARGET → SCAM SHIELD ================= */
(function shareTarget() {
  const p = new URLSearchParams(location.search);
  const shared = [p.get('title'), p.get('text'), p.get('url')].filter(Boolean).join('\n');
  if (shared && !p.get('action')) {
    setTimeout(() => {
      go('scam');
      $('scamInput').value = shared;
      analyzeScam();
    }, 900);
  }
})();
async function pasteAndAnalyze() {
  try {
    const t = await navigator.clipboard.readText();
    if (!t) return alert('Clipboard is empty.');
    $('scamInput').value = t;
    analyzeScam();
  } catch (e) { alert('Clipboard access denied — paste manually.'); }
}

/* ================= APP LOCK ================= */
$('appLockToggle').checked = !!store.get('applock', false);
$('appLockToggle').addEventListener('change', e => {
  if (e.target.checked && !store.get('vault_pin', null)) {
    alert('Set a Safe Space PIN first.');
    e.target.checked = false;
    return;
  }
  store.set('applock', e.target.checked);
});
(function appLockGate() {
  if (!store.get('applock', false) || !store.get('vault_pin', null) || store.get('stealth', false)) return;
  const ov = document.createElement('div');
  ov.style.cssText = 'position:fixed;inset:0;background:#0b1220;z-index:5000;display:flex;align-items:center;justify-content:center;flex-direction:column;gap:14px;padding:30px';
  ov.innerHTML = '<div style="font-size:50px">🛡️</div><div style="font-size:18px;font-weight:700">Raksha AI is locked</div>' +
    '<input id="alPin" type="password" inputmode="numeric" maxlength="8" placeholder="PIN" style="text-align:center;font-size:24px;letter-spacing:8px;max-width:220px">' +
    '<button id="alBtn" class="btn" style="max-width:220px">Unlock</button>';
  document.body.appendChild(ov);
  const tryUnlock = async () => {
    const pin = ov.querySelector('#alPin').value.trim();
    if (pin && (await pinHash(pin)) === store.get('vault_pin', null)) ov.remove();
    else { ov.querySelector('#alPin').value = ''; ov.querySelector('#alPin').placeholder = '✖ wrong'; }
  };
  ov.querySelector('#alBtn').addEventListener('click', tryUnlock);
  ov.querySelector('#alPin').addEventListener('keydown', e => { if (e.key === 'Enter') tryUnlock(); });
})();

